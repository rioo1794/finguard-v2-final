"""
modules/report_generator.py
Builds the FinGuard analysis report. Returns DOCX bytes (primary), TXT string (fallback).
"""
import io
from datetime import datetime

try:
    from docx import Document
    from docx.shared import Pt, RGBColor, Inches
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    _HAVE_DOCX = True
except ImportError:
    _HAVE_DOCX = False


def _verdict(safety_score):
    if safety_score >= 70:
        return "LOW RISK - Document appears largely compliant"
    if safety_score >= 40:
        return "MEDIUM RISK - Review flagged sections carefully"
    return "HIGH RISK - Significant concerns detected"


def _counts(compliance_results):
    return (
        sum(1 for r in compliance_results if r["status"] == "PASS"),
        sum(1 for r in compliance_results if r["status"] == "FAIL"),
        sum(1 for r in compliance_results if r["status"] == "UNCLEAR"),
    )


# --- plain text report ------------------------------------------------------
def generate_report_text(domain, url_or_filename, safety_score,
                         compliance_results, predatory_result,
                         cibil_result, multiparty_results,
                         fraud_result, precedents, plain_language):
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    pass_c, fail_c, unc_c = _counts(compliance_results)

    report = []
    report.append("=" * 70)
    report.append("FINGUARD AI - LEGAL DOCUMENT ANALYSIS REPORT")
    report.append("=" * 70)
    report.append("")
    report.append(f"Generated:       {timestamp}")
    report.append(f"Document:        {url_or_filename}")
    report.append(f"Document Domain: {domain}")
    report.append(f"Safety Score:    {safety_score}/100")
    report.append(f"Overall Verdict: {_verdict(safety_score)}")
    report.append("")
    report.append("COMPLIANCE SUMMARY")
    report.append("-" * 70)
    report.append(f"Passed:  {pass_c}")
    report.append(f"Failed:  {fail_c}")
    report.append(f"Unclear: {unc_c}")
    report.append("")
    for r in compliance_results:
        report.append(f"[{r['status']}] {r['check']}")
        report.append(r["result"])
        report.append("-" * 50)

    report += ["", "PREDATORY CLAUSE ANALYSIS", "-" * 70, str(predatory_result), ""]
    report += ["CIBIL CREDIT SCORE IMPACT", "-" * 70,
               str(cibil_result or "Not applicable for this document type"), ""]
    report += ["MULTI-PARTY INTEREST ANALYSIS", "-" * 70]
    for party, analysis in multiparty_results.items():
        report += ["", party, "-" * 40, str(analysis)]
    report += ["", "FRAUD PATTERN DETECTION", "-" * 70, str(fraud_result), ""]
    report += ["RELEVANT LEGAL PRECEDENTS", "-" * 70]
    for i, prec in enumerate(precedents, 1):
        report.append(f"{i}. {prec['case']} - {prec['court']} ({prec['year']})")
        report.append(f"   Citation:  {prec.get('citation', 'N/A')}")
        report.append(f"   Outcome:   {prec['outcome']}")
        report.append(f"   Relevance: {prec['relevance']}")
        report.append("")
    report += ["PLAIN LANGUAGE EXPLANATION", "-" * 70, str(plain_language), ""]
    report += ["GENERAL INFORMATION NOTICE", "-" * 70,
               "This report is general information only and is not legal advice. "
               "Consult a qualified Indian advocate before acting on it.", ""]
    report += ["REGULATORY REFERENCES", "-" * 70,
               "RBI Digital Lending Guidelines 2022/2025",
               "SEBI LODR Regulations 2015",
               "Transfer of Property Act 1882",
               "Hindu Marriage Act 1955",
               "Consumer Protection Act 2019",
               "Credit Information Companies Act 2005", ""]
    report += ["HELPLINES", "-" * 70,
               "Consumer: consumerhelpline.gov.in | 1915",
               "Banking:  cms.rbi.org.in",
               "Securities: scores.gov.in", ""]
    report += ["=" * 70, "Generated by FinGuard AI v2.0 - SAKEC AI & DS, Mumbai", "=" * 70]
    return "\n".join(report)


# --- docx report ------------------------------------------------------------
def generate_report_docx(domain, url_or_filename, safety_score,
                         compliance_results, predatory_result,
                         cibil_result, multiparty_results,
                         fraud_result, precedents, plain_language):
    if not _HAVE_DOCX:
        raise ImportError("python-docx is not installed. Run: pip install python-docx")

    doc = Document()

    # styles
    st = doc.styles["Normal"]
    st.font.name = "Calibri"
    st.font.size = Pt(11)

    def h1(text):
        p = doc.add_heading(text, level=1)
        return p

    def h2(text):
        return doc.add_heading(text, level=2)

    def para(text, italic=False, bold=False):
        p = doc.add_paragraph()
        run = p.add_run(str(text))
        run.italic = italic
        run.bold = bold
        return p

    def code_block(text):
        p = doc.add_paragraph()
        run = p.add_run(str(text))
        run.font.name = "Consolas"
        run.font.size = Pt(9.5)
        return p

    # title
    title = doc.add_heading("FinGuard AI - Legal Document Analysis Report", 0)
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER

    info = doc.add_paragraph()
    info.add_run("Generated: ").bold = True
    info.add_run(datetime.now().strftime("%Y-%m-%d %H:%M:%S"))
    doc.add_paragraph().add_run(f"Document: {url_or_filename}").bold = True
    doc.add_paragraph().add_run(f"Domain: {domain}").bold = True
    doc.add_paragraph().add_run(f"Safety Score: {safety_score}/100").bold = True
    doc.add_paragraph().add_run(f"Overall Verdict: {_verdict(safety_score)}").bold = True

    para("General information only. This is not legal advice.", italic=True)

    # compliance
    h1("Compliance Summary")
    pass_c, fail_c, unc_c = _counts(compliance_results)
    para(f"Passed: {pass_c}   Failed: {fail_c}   Unclear: {unc_c}")

    h2("Detailed Compliance Results")
    for r in compliance_results:
        h = doc.add_paragraph(style="List Bullet")
        run = h.add_run(f"[{r['status']}] {r['check']}")
        run.bold = True
        code_block(r["result"])

    # predatory
    h1("Predatory Clause Analysis")
    code_block(predatory_result)

    # cibil
    h1("CIBIL Credit Score Impact")
    code_block(cibil_result or "Not applicable for this document type")

    # multiparty
    h1("Multi-Party Interest Analysis")
    for party, analysis in multiparty_results.items():
        h2(party)
        code_block(analysis)

    # fraud
    h1("Fraud Pattern Detection")
    code_block(fraud_result)

    # precedents
    h1("Relevant Legal Precedents")
    for i, prec in enumerate(precedents, 1):
        h2(f"{i}. {prec['case']}")
        para(f"Court: {prec['court']} ({prec['year']})")
        if prec.get("citation"):
            para(f"Citation: {prec['citation']}")
        para(f"Outcome: {prec['outcome']}")
        para(f"Relevance: {prec['relevance']}")

    # plain language
    h1("Plain Language Explanation")
    code_block(plain_language)

    # regulatory + helplines
    h1("Regulatory References")
    for line in [
        "RBI Digital Lending Guidelines 2022/2025",
        "SEBI LODR Regulations 2015",
        "Transfer of Property Act 1882",
        "Hindu Marriage Act 1955",
        "Consumer Protection Act 2019",
        "Credit Information Companies Act 2005",
    ]:
        doc.add_paragraph(line, style="List Bullet")

    h1("Helplines")
    for line in [
        "Consumer: consumerhelpline.gov.in | 1915",
        "Banking: cms.rbi.org.in",
        "Securities: scores.gov.in",
    ]:
        doc.add_paragraph(line, style="List Bullet")

    # footer
    doc.add_paragraph()
    f = doc.add_paragraph()
    f.add_run("Generated by FinGuard AI v2.0 - SAKEC AI & DS, Mumbai").italic = True

    buf = io.BytesIO()
    doc.save(buf)
    buf.seek(0)
    return buf.getvalue()


# --- legacy entry point -----------------------------------------------------
def generate_report(domain, url_or_filename, safety_score,
                    compliance_results, predatory_result,
                    cibil_result, multiparty_results,
                    fraud_result, precedents, plain_language):
    """Kept for backwards compatibility: returns the plain-text report string."""
    return generate_report_text(
        domain, url_or_filename, safety_score, compliance_results,
        predatory_result, cibil_result, multiparty_results,
        fraud_result, precedents, plain_language,
    )